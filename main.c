/*
Лабораторная работа №3 - Работа с матрицами.
Необходимо создать матрицу размером N на M.
Размеры матрицы и сама матрица считываются из текстового файла.
Название файла необходимо передать как аргумент командной строки.

Действия с матрицей:
1. Найти S - сумма элементов главной диагонали матрицы.
2. Найти максимальный элемент в 3-ей строке матрицы.
3. Поменять местами найденный максимальный элемент и значение S.
*/

#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv) {
    if (argc != 2) {    // проверка, введено ли название текстового файла при вызове программы
        printf("Некорректный вызов программы. Введите: %s <filename>\n", argv[0]);
        return 1;
    }

    FILE *file = fopen(argv[1], "r");   // открытие текстового файла
    if (!file) {    // проверка, удалось ли открыть файл
        perror("Ошибка открытия файла");
        return 1;
    }

    int N, M;   // размеры матрицы по условию
    if (fscanf(file, "%d %d", &N, &M) != 2) {   // считываем значения размеров матрицы из первой строки файла. Проверяем, удалось ли считать
        printf("Ошибка чтения размеров матрицы\n");
        fclose(file);
        return 1;
    }

    int **matrix = (int **)malloc(N * sizeof(int *));   // выделение памяти под матрицу
     if (!matrix) {
        printf("Ошибка выделения памяти\n");
        fclose(file);
        return 1;
    }
    
    for (int i = 0; i < N; i++) {
        matrix[i] = (int *)malloc(M * sizeof(int));     // выделение памяти под строки матрицы
        if (!matrix[i]) {
            printf("Ошибка выделения памяти\n");
            // Освобождаем уже выделенную память
            for (int k = 0; k < i; k++) free(matrix[k]);
            free(matrix);
            fclose(file);
            return 1;
        }
        
        for (int j = 0; j < M; j++) {
            if (fscanf(file, "%d", &matrix[i][j]) != 1) {   // заполняем матрицу значениями из файла
                printf("Ошибка чтения элемента матрицы\n");
                fclose(file);
                return 1;
            }
        }
    }
    fclose(file);

    printf("Исходная матрица %dx%d:\n", N, M);     // выводим матрицу из текстового файла для проверки корректности работы программы и сравнения с результатом преобразований
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < M; j++) {
            printf("%d ", matrix[i][j]);
        }
        printf("\n");
    }

    // 1. Сумма элементов главной диагонали
    // Для неквадратной матрицы берем диагональ от [0][0] до [min(N,M)-1][min(N,M)-1]
    int S = 0;
    int min_size = (N < M) ? N : M; // находим минимальный размер матрицы
    for (int i = 0; i < min_size; i++) {
        S += matrix[i][i];  // складываем диагональные элементы
    }
    printf("Сумма элементов главной диагонали: %d\n", S);

    // 2. Максимальный элемент в 3-ей строке
    if (N < 3) {    // проверяем, есть ли в матрице 3 строки
        printf("Ошибка: матрица содержит меньше 3 строк\n");
        // Освобождение памяти
        for (int i = 0; i < N; i++) free(matrix[i]);
        free(matrix);
        return 1;
    }

    int max_element = matrix[2][0]; // пусть максимальным будет первый элемент 3 строки
    int max_column = 0;     // столбец, в котором находится максимальный элемент 3 строки
    for (int j = 1; j < M; j++) {
        if (matrix[2][j] > max_element) {   // если последующий элемент больше максимального
            max_element = matrix[2][j];     // записываем его в качестве максимального
            max_column = j;                 // записываем номер столбца, в котором находится максимальный элемент
        }
    }
    printf("Максимальный элемент в 3-ей строке: %d (столбец %d)\n", max_element, max_column + 1);

    // 3. Обмен значений
    printf("Меняем местами %d и %d\n", S, max_element);
    int temp = matrix[2][max_column];   // вспомогательная переменная
    matrix[2][max_column] = S;      // меняем максимальный элемент на S
    S = temp;                       // меняем S на максимальный элемент

    // Вывод измененной матрицы
    printf("Измененная матрица:\n");
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < M; j++) {
            printf("%d ", matrix[i][j]);
        }
        printf("\n");
    }

    // Освобождение памяти
    for (int i = 0; i < N; i++) free(matrix[i]);
    free(matrix);

    return 0;

}
